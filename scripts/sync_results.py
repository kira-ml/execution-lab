"""Copy generated demo evidence into the committed docs tree.

`results/` is regenerated and git-ignored. `docs/RESULTS.md`, `docs/figures/`,
and `docs/demo-manifest.json` are the committed evidence. Run this after
`execution-lab demo`.
"""

from __future__ import annotations

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results" / "demo"
DOCS = ROOT / "docs"

HEADER = """# Results — Execution & Market-Impact Lab

> **Evidence note:** this file is a committed copy of `results/demo/report.md`,
> generated by `execution-lab demo` from the checked-in synthetic panel (seed
> `20261108`). The `results/` directory is regenerated and git-ignored; this copy
> and the figures in `docs/figures/` are the evidence. The demo is a method
> demonstration on synthetic data, not an empirical claim about real ETFs.

---

"""


FIGURES = """

---

## Figures

![Schedule frontier](figures/fig_schedule_frontier.png)

![Cost curve](figures/fig_cost_curve.png)

![Ranking heatmap](figures/fig_ranking_heatmap.png)

![Impact sensitivity](figures/fig_k_sensitivity.png)

![Capacity stress](figures/fig_aum_sensitivity.png)

![Cost decomposition](figures/fig_cost_decomposition.png)
"""


def main() -> None:
    body = (RESULTS / "report.md").read_text(encoding="utf-8")
    lines = body.splitlines()
    if lines and lines[0].startswith("# "):
        body = "\n".join(lines[1:]).lstrip("\n")
    (DOCS / "RESULTS.md").write_text(
        HEADER + "## Generated report\n\n" + body + FIGURES,
        encoding="utf-8",
    )
    figures = DOCS / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    for path in sorted(RESULTS.glob("fig_*.png")):
        shutil.copy2(path, figures / path.name)
    manifest = RESULTS / "manifest.json"
    if manifest.exists():
        shutil.copy2(manifest, DOCS / "demo-manifest.json")
    print(f"wrote {DOCS / 'RESULTS.md'}")
    print(f"copied {len(list(figures.glob('fig_*.png')))} figures to {figures}")


if __name__ == "__main__":
    main()
